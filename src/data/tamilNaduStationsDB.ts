// Helper to convert TamilNaduStationMaster to full Station type for the UI
export function convertToStationModel(station: TamilNaduStationMaster): Station {
  const isCbe = station.code === 'CBE';
  const isMas = station.code === 'MAS';
  const isMtp = station.code === 'MTP';

  const floors = isCbe
    ? [
        { id: 'L2' as const, name: 'Level 2 - Skybridge FOB & Glass Elevators', label: 'L2', description: 'Pedestrian skybridge connecting all platforms with tactile guide' },
        { id: 'G' as const, name: 'Ground - Main Concourse & Platforms 1-6', label: 'G', description: 'Ticketing, VIP waiting lounge, AC food court, pre-paid autorickshaws' },
        { id: 'L1' as const, name: 'Level -1 - Heritage Subway Underpass', label: 'L1', description: 'Rapid track-crossing tunnel with step-free ramps' },
      ]
    : [
        { id: 'L2' as const, name: 'Foot Overbridge (FOB)', label: 'L2', description: 'Overhead passenger bridge with stairs and lift access' },
        { id: 'G' as const, name: `Ground Concourse & Platforms (1-${station.platforms})`, label: 'G', description: 'Ticket counters, waiting halls, refreshment stalls, exit' },
        { id: 'L1' as const, name: 'Pedestrian Subway', label: 'L1', description: 'Track crossing underpass' },
      ];

  const pois = [
    {
      id: `${station.code.toLowerCase()}-plat-1`,
      name: `Platform 1 (${station.code} Main)`,
      category: 'platform' as const,
      floor: 'G' as const,
      x: 40,
      y: 50,
      walkingTimeMin: 1,
      description: `Primary main line platform at ${station.name}`,
      accessible: true,
      icon: 'train',
      platformStatus: 'OPERATIONAL',
    },
    {
      id: `${station.code.toLowerCase()}-plat-2`,
      name: `Platform 2`,
      category: 'platform' as const,
      floor: 'G' as const,
      x: 60,
      y: 50,
      walkingTimeMin: 2,
      description: `Through express & passenger trains`,
      accessible: true,
      icon: 'train',
      platformStatus: 'OPERATIONAL',
    },
    {
      id: `${station.code.toLowerCase()}-ticket`,
      name: 'UTS & PRS Ticket Counter',
      category: 'service' as const,
      floor: 'G' as const,
      x: 25,
      y: 35,
      walkingTimeMin: 1,
      description: 'Reserved & Unreserved ticket booking windows',
      accessible: true,
      icon: 'confirmation_number',
    },
    {
      id: `${station.code.toLowerCase()}-restroom`,
      name: 'Accessible Restrooms',
      category: 'restroom' as const,
      floor: 'G' as const,
      x: 30,
      y: 65,
      walkingTimeMin: 2,
      description: 'Divyangjan step-free accessible clean toilets',
      accessible: true,
      icon: 'wc',
    },
    {
      id: `${station.code.toLowerCase()}-lift`,
      name: 'Passenger Elevator (Lift)',
      category: 'elevator' as const,
      floor: 'G' as const,
      x: 45,
      y: 52,
      walkingTimeMin: 1,
      description: 'Glass elevator connecting Ground to FOB L2',
      accessible: true,
      icon: 'elevator',
    },
  ];

  const departures = station.popularTrains.slice(0, 4).map((trainNo, idx) => ({
    id: `${station.code.toLowerCase()}-dep-${trainNo}`,
    trainNumber: trainNo,
    destination: `Express via ${station.district}`,
    operator: 'Southern Railway',
    time: ['06:00 AM', '10:30 AM', '03:05 PM', '07:45 PM', '10:40 PM'][idx % 5],
    status: 'LIVE' as const,
    platform: `Platform ${(idx % station.platforms) + 1}`,
    delayMin: 0,
    trackColor: station.tagColor,
  }));

  return {
    id: station.id,
    name: station.name,
    code: station.code,
    location: `${station.name}, ${station.district} District, Tamil Nadu`,
    city: station.district,
    state: station.state,
    country: 'India',
    latitude: station.latitude,
    longitude: station.longitude,
    platforms: station.platforms,
    facilitiesCount: station.facilitiesCount,
    has3D: station.has3D,
    hasAR: station.hasAR,
    has2D: station.has2D,
    mappingMode: station.mappingMode,
    mapVersion: 'v2.4.0',
    tag: station.tag,
    tagColor: station.tagColor,
    bookmarked: isCbe || isMas || isMtp,
    description: station.description,
    floors,
    pois,
    departures,
    lastVerifiedAt: '2026-10-10T12:00:00+05:30',
    source: `SOUTHERN_RAILWAY_${station.division.split(' ')[0].toUpperCase()}_DIV_VERIFIED`,
  };
}

