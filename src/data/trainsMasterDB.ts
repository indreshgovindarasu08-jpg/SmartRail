// Realtime Status Generator with dynamic countdowns
export function generateTrainStatus(trainNumber: string, userStationCode: string = 'CBE'): TrainStatus | null {
  const train = MASTER_TRAINS_LIST.find((t) => t.number === trainNumber);
  if (!train) return null;

  const stops = TRAIN_STOPS_MAP[trainNumber] || [
    {
      stopSequence: 1,
      stationCode: train.originCode,
      stationName: train.originName,
      city: train.originCity,
      scheduledArrival: '--',
      scheduledDeparture: train.departureTime,
      delayMinutes: 0,
      platform: 'Platform 1',
      platformConfirmed: true,
      distanceFromOriginKm: 0,
      status: 'PASSED',
    },
    {
      stopSequence: 2,
      stationCode: train.destinationCode,
      stationName: train.destinationName,
      city: train.destinationCity,
      scheduledArrival: train.arrivalTime,
      scheduledDeparture: '--',
      delayMinutes: 0,
      platform: train.number === '12681' ? 'Platform 5' : 'Platform 2',
      platformConfirmed: true,
      distanceFromOriginKm: train.totalDistanceKm,
      status: 'CURRENT',
      isUserStation: true,
    },
  ];

  let state: 'RUNNING' | 'ON_TIME' | 'DELAYED' | 'ARRIVING' | 'DEPARTED' = 'RUNNING';
  let delayMinutes = 0;
  let assignedPlatform = 'Platform 2';
  let countdownSeconds = 2400;

  if (trainNumber === '12681') {
    state = 'ARRIVING';
    delayMinutes = 0;
    assignedPlatform = 'Platform 5';
    countdownSeconds = 754; // exactly 12m 34s
  } else if (trainNumber === '20644' || trainNumber === '20601') {
    state = 'ON_TIME';
    delayMinutes = 0;
    assignedPlatform = 'Platform 1';
    countdownSeconds = 1800;
  } else if (trainNumber === '12676' || trainNumber === '12635') {
    state = 'RUNNING';
    delayMinutes = 0;
    assignedPlatform = 'Platform 2';
    countdownSeconds = 2400;
  } else if (trainNumber === '12678' || trainNumber === '12637') {
    state = 'RUNNING';
    delayMinutes = 0;
    assignedPlatform = 'Platform 3';
    countdownSeconds = 3600;
  } else if (trainNumber === '16381') {
    state = 'DELAYED';
    delayMinutes = 15;
    assignedPlatform = 'Platform 4';
    countdownSeconds = 5400;
  } else if (trainNumber === '06815' || trainNumber === '06136') {
    state = 'RUNNING';
    delayMinutes = 0;
    assignedPlatform = 'Platform 6';
    countdownSeconds = 4200;
  } else if (trainNumber === '12631' || trainNumber === '12633') {
    state = 'ON_TIME';
    delayMinutes = 0;
    assignedPlatform = 'Platform 1';
    countdownSeconds = 1500;
  } else {
    // Deterministic platform and timing for any other Tamil Nadu train
    const numInt = parseInt(trainNumber.replace(/\D/g, '') || '2', 10);
    const platformNum = (numInt % 6) + 1;
    assignedPlatform = `Platform ${platformNum}`;
    state = numInt % 7 === 0 ? 'DELAYED' : numInt % 3 === 0 ? 'ON_TIME' : 'RUNNING';
    delayMinutes = state === 'DELAYED' ? (numInt % 20) + 5 : 0;
    countdownSeconds = 1200 + ((numInt % 45) * 60);
  }

  const currentStnCode = train.originCode;
  const currentStnName = train.originName;

  return {
    trainNumber: train.number,
    trainName: train.name,
    state,
    delayMinutes,
    currentStationCode: trainNumber === '12681' ? 'TUP' : currentStnCode,
    currentStationName: trainNumber === '12681' ? 'Tiruppur Railway Station' : currentStnName,
    nextStationCode: userStationCode,
    nextStationName: userStationCode === 'CBE' ? 'Coimbatore Junction' : `${userStationCode} Station`,
    lastUpdatedTime: new Date(Date.now() - 32000).toISOString(),
    etaAtDestination: train.arrivalTime,
    targetStationCode: userStationCode,
    targetStationName: `${userStationCode} Station`,
    assignedPlatform,
    platformStatus: 'CONFIRMED',
    freshness: {
      state: 'LIVE',
      updatedAt: new Date(Date.now() - 32000).toISOString(),
      source: 'SOUTHERN_RAILWAY_LIVE_TELEMETRY',
      secondsAgo: 32,
    },
    speedKmh: trainNumber === '12681' ? 84 : train.type.includes('Vande') ? 110 : 75,
    stops,
    userStationCountdownSeconds: countdownSeconds,
    isArrivingSoon: countdownSeconds <= 900,
  };
}
